let globalCustomExercises: Exercise[] = [];

export function setCustomExercises(customExercises: Exercise[]) {
  globalCustomExercises = customExercises || [];
}

export function getAllExercises(extraCustom?: Exercise[]): Exercise[] {
  const customList = extraCustom || globalCustomExercises;
  const merged = [...EXERCISES, ...customList];
  const seen = new Set<string>();
  return merged.filter((item) => {
    if (seen.has(item.id)) return false;
    seen.add(item.id);
    return true;
  });
}

export function findExercise(id: string, extraCustom?: Exercise[]): Exercise | undefined {
  return getAllExercises(extraCustom).find((e) => e.id === id);
}

